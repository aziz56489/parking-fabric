package com.parking.dto;

import com.parking.entity.IssueType;
import com.parking.entity.SpotStatus;
import com.parking.entity.SpotType;

import java.math.BigDecimal;
import java.util.List;

public final class ParkingRequests {

    private ParkingRequests() {
    }

    public record CreateParkingAreaRequest(String name) {
    }

    public record LayoutRequest(String layout, List<Spot> spots) {

        /** {@code pricePerHour} is optional: without it the spot uses the default price. */
        public record Spot(String number, SpotType type, BigDecimal pricePerHour) {
        }
    }

    public record SpotUpdateRequest(SpotType type, SpotStatus status) {
    }

    /** {@code userId} is a random id generated by the mobile app until the API has authentication. */
    public record ReservationRequest(Integer spotId, String userId) {
    }

    public record IssueRequest(IssueType type, String description) {
    }

    /** SCRUM-88: the reservation the user did not pay for, and an optional note from the ticket counter. */
    public record NonPayingReportRequest(Integer reservationId, String note) {
    }
}
